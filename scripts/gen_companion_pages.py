#!/usr/bin/env python3
"""Generate published docs pages from repo/templates and repo/labs.

Source of truth stays in repo/; generated pages land in docs/appendices/
(chNN-templates.md) and docs/labs/ (chNN.md). Run before mkdocs build.

Chapters are released incrementally: any chNN present under repo/templates/
is considered released and gets its pages generated.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GH = "https://github.com/hallieren/ai-agent-evaluation/blob/main"
GH_TREE = "https://github.com/hallieren/ai-agent-evaluation/tree/main"
BANNER = "<!-- Generated by scripts/gen_companion_pages.py. Do not edit directly; sources live under repo/ -->\n\n"


def demote(md: str) -> str:
    """Demote every ATX heading one level, skipping fenced code blocks."""
    out, fenced = [], False
    for line in md.splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
        if not fenced and line.startswith("#"):
            line = "#" + line
        out.append(line)
    return "\n".join(out) + "\n"


def gen_templates(ch: str) -> int:
    src_dir = ROOT / "repo" / "templates" / ch
    files = sorted(src_dir.glob("*.md"))
    assert files, f"no templates in {src_dir}"
    n = int(ch[2:])
    parts = [BANNER, f"# Chapter {n} templates\n\n",
             f'!!! note ""\n    This page is generated from [`repo/templates/{ch}/`]({GH_TREE}/repo/templates/{ch}/); the repo holds the latest version.\n\n']
    for f in files:
        rel = f"repo/templates/{ch}/{f.name}"
        parts.append(demote(f.read_text(encoding="utf-8")))
        parts.append(f"\n> Source file: [`{rel[5:]}`]({GH}/{rel})\n\n---\n\n")
    out = ROOT / "docs" / "appendices" / f"{ch}-templates.md"
    out.write_text("".join(parts).rstrip("-\n ") + "\n", encoding="utf-8", newline="\n")
    return len(files)


def gen_lab(ch: str) -> None:
    src_dir = ROOT / "repo" / "labs" / ch
    readme = (src_dir / "README.md").read_text(encoding="utf-8")
    files = sorted(p.name for p in src_dir.iterdir()
                   if p.is_file() and p.name != "README.md")
    listing = "\n".join(
        f"- [`{name}`]({GH}/repo/labs/{ch}/{name})" for name in files)
    body = (BANNER + readme.rstrip() + "\n\n---\n\n## Files in this lab\n\n"
            + f"Full directory: [`repo/labs/{ch}/`]({GH_TREE}/repo/labs/{ch}/)\n\n"
            + listing + "\n")
    out = ROOT / "docs" / "labs" / f"{ch}.md"
    out.write_text(body, encoding="utf-8", newline="\n")


def main() -> None:
    (ROOT / "docs" / "labs").mkdir(exist_ok=True)
    chapters = sorted(p.name for p in (ROOT / "repo" / "templates").iterdir()
                      if p.is_dir() and p.name.startswith("ch"))
    assert chapters, "no released chapters under repo/templates/"
    total = 0
    for ch in chapters:
        total += gen_templates(ch)
        gen_lab(ch)
    print(f"generated {len(chapters)} template pages ({total} templates) "
          f"+ {len(chapters)} lab pages")


if __name__ == "__main__":
    main()
